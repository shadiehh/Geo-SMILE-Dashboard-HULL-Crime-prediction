"""Bootstrap confidence intervals over the R=10 SMILE-reseed replicates
generated by bootstrap_seed_replicates.py:
  (a) Feature-branch fidelity ordering (Table 4.7, all 10 candidate models).
  (b) Geo-branch top-20 overlap counts (Figure 4.8, 5 models: xgboost,
      catboost, lightgbm, gp, dl).

Method: paired bootstrap over the 10 reseed INDICES (seeds 42..51), not
independent per-model resampling -- every model/pair was evaluated at the
SAME 10 seeds (same mask/perturbation draws, since the model-specific
response is what varies), so a bootstrap resample draws which of the 10
seed-indices to include (with replacement) ONCE per replicate and applies
that same draw to every model/pair. This preserves the real experiment's
paired structure instead of adding spurious extra variance from treating
each model's reseeds as independent.

For (a): each bootstrap replicate recomputes every model's mean R2 (and
weighted R2) over the resampled seeds, and the resulting rank ordering.
Reports per-model 95% percentile CIs and, since the point of Table 4.7 is
an ORDERING, the fraction of bootstrap replicates in which each adjacent
pair in the observed ranking is preserved (adjacent-pair "win probability").

For (b): each bootstrap replicate recomputes, per model pair, the mean
top-20 overlap count over the resampled seeds. Reports per-pair 95%
percentile CIs.

B = 10,000 resamples, percentile method, seed 0 for the resampling RNG
itself (unrelated to the SMILE seeds already used to generate the data).

Writes outputs/bootstrap_replicates/{feature_fidelity_bootstrap_summary,
geo_overlap_bootstrap_summary}.csv.
"""

from __future__ import annotations

from itertools import combinations
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent
DEST = ROOT / "outputs" / "bootstrap_replicates"
B = 10_000
RNG_SEED = 0


def _log(msg: str) -> None:
    print(msg, flush=True)


def bootstrap_feature(path: Path) -> pd.DataFrame:
    df = pd.read_csv(path)
    models = sorted(df["model"].unique())
    seeds = sorted(df["seed"].unique())
    n_seeds = len(seeds)
    # (n_models, n_seeds) matrices, columns aligned to `seeds` order
    r2_mat = df.pivot(index="model", columns="seed", values="r2").loc[models, seeds].to_numpy()
    w_mat = df.pivot(index="model", columns="seed", values="weighted_r2").loc[models, seeds].to_numpy()

    point_r2 = r2_mat.mean(axis=1)
    point_w = w_mat.mean(axis=1)
    observed_order = np.argsort(-point_r2)  # descending

    rng = np.random.default_rng(RNG_SEED)
    boot_r2_means = np.empty((B, len(models)))
    boot_w_means = np.empty((B, len(models)))
    adjacent_preserved = np.zeros(len(models) - 1)

    for b in range(B):
        idx = rng.integers(0, n_seeds, size=n_seeds)
        boot_r2_means[b] = r2_mat[:, idx].mean(axis=1)
        boot_w_means[b] = w_mat[:, idx].mean(axis=1)
        order_b = boot_r2_means[b]
        for i in range(len(models) - 1):
            a, c = observed_order[i], observed_order[i + 1]
            if order_b[a] >= order_b[c]:
                adjacent_preserved[i] += 1
    adjacent_preserved /= B

    r2_ci_lo, r2_ci_hi = np.percentile(boot_r2_means, [2.5, 97.5], axis=0)
    w_ci_lo, w_ci_hi = np.percentile(boot_w_means, [2.5, 97.5], axis=0)

    rows = []
    for rank, mi in enumerate(observed_order, start=1):
        row = {
            "rank": rank, "model": models[mi],
            "r2_mean": point_r2[mi], "r2_ci_lo": r2_ci_lo[mi], "r2_ci_hi": r2_ci_hi[mi],
            "weighted_r2_mean": point_w[mi], "weighted_r2_ci_lo": w_ci_lo[mi], "weighted_r2_ci_hi": w_ci_hi[mi],
        }
        if rank <= len(models) - 1:
            row["p_rank_preserved_vs_next"] = adjacent_preserved[rank - 1]
        rows.append(row)
    return pd.DataFrame(rows)


def bootstrap_geo(path: Path) -> pd.DataFrame:
    df = pd.read_csv(path)
    models = sorted(df["model"].unique())
    seeds = sorted(df["seed"].unique())
    n_seeds = len(seeds)
    # sets[(model, seed)] = set of top-20 lsoa21cd
    sets = {(m, s): set(g["lsoa21cd"]) for (m, s), g in df.groupby(["model", "seed"])}

    pairs = list(combinations(models, 2))
    # overlap_mat[pair_idx, seed_idx]
    overlap_mat = np.array([
        [len(sets[(a, s)] & sets[(b, s)]) for s in seeds]
        for a, b in pairs
    ], dtype=float)

    point = overlap_mat.mean(axis=1)
    rng = np.random.default_rng(RNG_SEED)
    boot_means = np.empty((B, len(pairs)))
    for b in range(B):
        idx = rng.integers(0, n_seeds, size=n_seeds)
        boot_means[b] = overlap_mat[:, idx].mean(axis=1)
    ci_lo, ci_hi = np.percentile(boot_means, [2.5, 97.5], axis=0)

    rows = []
    for i, (a, b) in enumerate(pairs):
        rows.append({
            "model_a": a, "model_b": b,
            "overlap_mean": point[i], "overlap_ci_lo": ci_lo[i], "overlap_ci_hi": ci_hi[i],
        })
    return pd.DataFrame(rows)


def main() -> None:
    feat_path = DEST / "feature_fidelity_replicates.csv"
    geo_path = DEST / "geo_top20_replicates.csv"

    if feat_path.exists():
        feat_summary = bootstrap_feature(feat_path)
        out = DEST / "feature_fidelity_bootstrap_summary.csv"
        feat_summary.to_csv(out, index=False)
        _log(f"Feature fidelity bootstrap ({B} resamples) -> {out}")
        _log(feat_summary.to_string(index=False))
    else:
        _log(f"Skipped Feature bootstrap: {feat_path} not found")

    if geo_path.exists():
        geo_summary = bootstrap_geo(geo_path)
        out = DEST / "geo_overlap_bootstrap_summary.csv"
        geo_summary.to_csv(out, index=False)
        _log(f"\nGeo top-20 overlap bootstrap ({B} resamples) -> {out}")
        _log(geo_summary.to_string(index=False))
    else:
        _log(f"Skipped Geo bootstrap: {geo_path} not found")


if __name__ == "__main__":
    main()
