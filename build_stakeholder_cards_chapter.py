"""Combine the six Chapter 6 stakeholder cards into stakeholder_cards_chapter6.tex.

    python build_stakeholder_cards_chapter.py

Shared macros are defined once; each subsection and its card share one page (cards are not
floated and are scaled down, with graphicx only, when taller than the space left on the page)."""
import re
from pathlib import Path

N = Path(__file__).resolve().parent / "outputs" / "stakeholder_narratives"
ORDER = ["public", "planner", "police", "manager", "researcher", "governance"]

HEADER = r"""% =========================================================
% Chapter 6 stakeholder cards (Resident / Public, City Planner, Police, Manager, Researcher,
% Governance). Built from <stakeholder>_card.tex by combining them: shared macros are defined
% once here, and each stakeholder subsection (heading, short introduction and card) sits on its
% own page. Cards are not floated ([H]) so each stays on the page of its heading.
% Fit: each card is set single-spaced and, only if it is taller than the space left on the page
% below its heading and introduction, scaled down to fit (\cardavail, measured on each page), so
% the subsection and its card share one page under any thesis geometry or line spacing.
% Text and tiles of every card are generated by the dashboard LLM pipeline
% (generate_card_narrative.py, master prompt geosmile-hull-v8 + card-mode addendum); prompts,
% evidence, raw output and checks are in <stakeholder>_card_llm.json.
%
% Preamble: \usepackage[most]{tcolorbox}, xcolor, graphicx, float (nothing else).
% Chapter6/figs/ needs every <stakeholder>_card_llm_content_openai.tex and the panel images
% named in each figure below.
% =========================================================

\definecolor{cardInk}{HTML}{12171C}
\definecolor{cardMuted}{HTML}{57646D}
\definecolor{cardTeal}{HTML}{1F4E5F}
\definecolor{cardPink}{HTML}{FCE4EC}
\definecolor{cardWine}{HTML}{8A0033}
\definecolor{cardRule}{HTML}{D9DEE2}

% Figures and key terms the model marked: one pink highlight in the running text's own font.
\providecommand{\hlpink}[1]{\begingroup\setlength{\fboxsep}{0.6pt}\colorbox{cardPink}{\textcolor{cardWine}{#1}}\endgroup}
\providecommand{\pv}[1]{\hlpink{#1}}
\providecommand{\kt}[1]{\hlpink{#1}}
\providecommand{\roletag}[1]{\tcbox[on line, colback=cardTeal, colframe=cardTeal, arc=2.5mm,
  boxsep=0pt, left=6pt, right=6pt, top=3pt, bottom=3pt]{\color{white}\sffamily\bfseries #1}}
\providecommand{\kicker}[1]{{\color{cardMuted}\sffamily\small\bfseries #1}}
% Stat tile: figure over a short label, four to a row; each card sets its width and height group.
\providecommand{\tile}[2]{\begin{tcolorbox}[enhanced, nobeforeafter, width=\cardtilewidth,
  equal height group=\cardtilegroup, colback=cardPink, frame hidden, arc=2mm,
  left=5pt, right=3pt, top=3pt, bottom=3pt, valign=top, before upper=\raggedright]
  {\bfseries\color{cardWine}#1}\par\vspace{1pt}
  {\sffamily\color{cardMuted}#2}\end{tcolorbox}}
% One dashboard panel under its numbered heading, image at #2 of the column width.
\providecommand{\dashpanel}[3]{\kicker{#1}\par\vspace{2pt}%
  {\centering\includegraphics[width=#2\linewidth]{#3}\par}}
% Space left on the page for the card, measured after each introduction; room kept for the caption.
\newlength{\cardavail}
\providecommand{\cardcaptionroom}{4.5\baselineskip}
\providecommand{\measurecard}{\par\setlength{\cardavail}{\dimexpr\pagegoal-\pagetotal-\cardcaptionroom\relax}}
% Each card is set in \cardbox first, then printed at full size or, if taller than \cardavail,
% scaled to that height with graphicx's \resizebox (no extra package needed).
\newsavebox{\cardbox}
\newlength{\cardheight}
\providecommand{\usecardbox}{\setlength{\cardheight}{\dimexpr\ht\cardbox+\dp\cardbox\relax}%
  {\centering\ifdim\cardheight>\cardavail\resizebox*{!}{\cardavail}{\usebox{\cardbox}}\else\usebox{\cardbox}\fi\par}}
% Placeholders, replaced by each card's generated content file.
\providecommand{\cardHeadline}{[headline]}
\providecommand{\cardSecA}{[section 01]}
\providecommand{\cardSecB}{[section 02]}
\providecommand{\cardFooter}{[footer]}
\providecommand{\cardModel}{[model]}
\providecommand{\cardTileA}{\tile{--}{--}}
\providecommand{\cardTileB}{\tile{--}{--}}
\providecommand{\cardTileC}{\tile{--}{--}}
\providecommand{\cardTileD}{\tile{--}{--}}
"""

OPEN_BOX = r"\begin{tcolorbox}[enhanced, colback=white"
FIT_OPEN = "\\begin{lrbox}{\\cardbox}\\begin{minipage}{\\linewidth}\n" + OPEN_BOX
SPACING_FROM = r"fontupper=\sffamily\normalsize"
SPACING_TO = r"fontupper=\linespread{1}\sffamily\normalsize"
CLOSE_FROM = "\\end{tcolorbox}\n\\caption"
CLOSE_TO = "\\end{tcolorbox}\n\\end{minipage}\\end{lrbox}\n\\usecardbox\n\\caption"

parts = [HEADER]
for s in ORDER:
    t = (N / f"{s}_card.tex").read_text(encoding="utf-8")
    head = re.search(r"\\subsection\{.*?\\par\\medskip", t, re.S).group(0)
    defs = "\n".join(re.findall(r"^\\def\\(?:cardtile\w+|managertileheight)\{.*\}$", t, re.M))
    inp = re.search(r"^\\input\{Chapter6/figs/\w+_card_llm_content_openai\.tex\}$", t, re.M).group(0)
    fig = re.search(r"\\begin\{figure\}\[!htbp\].*?\\end\{figure\}", t, re.S).group(0)
    for a, b in ((r"\begin{figure}[!htbp]", r"\begin{figure}[H]"), (OPEN_BOX, FIT_OPEN),
                 (SPACING_FROM, SPACING_TO), (CLOSE_FROM, CLOSE_TO)):
        assert fig.count(a) == 1, (s, a)
        fig = fig.replace(a, b)
    # The section heading names the stakeholder, so the card's role tag is dropped.
    fig, n = re.subn(r"\\roletag\{[^}]*\}\\par\\smallskip\n", "", fig)
    assert n == 1, (s, "roletag")
    # Provenance is stated once in the section introduction (stakeholder_cards_section_intro.tex).
    fig, n = re.subn(r"\s*Text(?:,\s+tiles)?\s+and\s+\\pv\{highlights\}\s+generated\s+by\s+\\cardModel\{\}\s*"
                     r"\(prompt\s+geosmile-hull-v8,\s+card\s+mode\)\.", "", fig)
    assert n == 1, (s, "provenance")
    parts.append(f"""
% =========================================================
\\clearpage
{inp}
{head}
{defs}
\\measurecard

{fig}
""")
(N / "stakeholder_cards_chapter6.tex").write_text("\n".join(parts), encoding="utf-8")
print("written", sum(p.count("\n") for p in parts), "lines")
