@st.cache_data(show_spinner=False)
def published_card(stakeholder: str) -> dict | None:
    path = HULL_ROOT / CARDS_DIR / f"{stakeholder}_card_llm.json"
    if not path.exists():
        return None
    record = json.loads(path.read_text(encoding="utf-8"))
    run = (record.get("runs") or {}).get("openai") or {}
    return run if run.get("ok") else None


def _tiles(tiles: list[dict]) -> str:
    cells = "".join(
        f"<div class='gs-tile'><div class='gs-tile-value'>{html.escape(cm._bare(str(t.get('value', ''))))}</div>"
        f"<div class='gs-tile-label'>{html.escape(cm._bare(str(t.get('label', ''))))}</div></div>"
        for t in tiles)
    return f"<div class='gs-tiles'>{cells}</div>"


def _inline(text: str) -> str:
    return cm.marked_html(text).replace("<p style='margin:0 0 0.6rem 0; line-height:1.55;'>", "").replace("</p>", "")


def render_card(stakeholder: str) -> None:
    run = published_card(stakeholder)
    if run is None:
        st.warning("This card has not been published yet. Run generate_card_narrative.py.")
        return
    card = run["content"]
    subtitle, panels_titles, heads, n_tiles, note = CARD_LAYOUT[stakeholder]
    d = stakeholder_data()
    panels = stakeholder_panels(f"{stakeholder}_short", cm.CENTRE, d.default_contrast(cm.CENTRE))
    checks = "Checks passed" if run["checks"]["ok"] else "Checks failed: " + "; ".join(run["checks"]["problems"])
    meta = (f"Text generated by {html.escape(run['model'])} at temperature 0 "
            f"· prompt {html.escape(run['prompt_version'])} + card addendum "
            f"· {html.escape(run['timestamp'][:10])} · {html.escape(checks)}")
    _card(stakeholder, subtitle, panels_titles, heads, panels, card, n_tiles, note, meta)


def _card(stakeholder: str, subtitle: str, panels_titles, heads, panels, card: dict, n_tiles: int, note: str,
          meta: str) -> None:
    with st.container(border=True):
        st.markdown(
            f"<div class='gs-kicker'>{html.escape(STAKEHOLDERS[stakeholder])} · {html.escape(subtitle)}</div>"
            f"<div class='gs-headline'>{_inline(card['headline'])}</div>", unsafe_allow_html=True)
        left, right = st.columns(2, gap="large")
        for col, title, head, key, (image, _, caption) in zip((left, right), panels_titles, heads,
                                                              ("section_01", "section_02"), panels):
            with col:
                st.markdown(f"<div class='gs-kicker'>{html.escape(title)}</div>", unsafe_allow_html=True)
                st.image(image, width="stretch")
                st.markdown(f"<div class='gs-caption'>{html.escape(caption)}</div>", unsafe_allow_html=True)
                if head:
                    st.markdown(f"<div class='gs-kicker'>{html.escape(head)}</div>", unsafe_allow_html=True)
                st.markdown(f"<div class='gs-body'>{cm.marked_html(card[key])}</div>", unsafe_allow_html=True)
        st.markdown(_tiles(card["tiles"][:n_tiles]), unsafe_allow_html=True)
        st.markdown(f"<div class='gs-foot'>{html.escape(card['footer'])} {html.escape(note)}<br>"
                    f"<span class='gs-meta'>{meta}</span></div>", unsafe_allow_html=True)


AREA_PANEL_TITLES = {
    "public": ("01 · Across Hull", "02 · This area"),
    "planner": ("01 · GeoSensitivity", "02 · Built-environment share"),
    "police": ("01 · Recent or long-run signal", "02 · Recorded change"),
}


def _area_name(lsoa: str) -> str:
    d = stakeholder_data()
    return f"{d.short(lsoa)} · {d.place(lsoa)}" if d.place(lsoa) else d.short(lsoa)


def _run_live(bundle, stakeholder: str, lsoa: str, mode: str, label: str):
    """Generate and Regenerate buttons; the latest result for this area, role and length, or None."""
    store = st.session_state.setdefault("live_results", {})
    key = (stakeholder, lsoa, mode)
    generate, again, _ = st.columns([1.2, 0.8, 2], vertical_alignment="center")
    first = generate.button(f"Generate {label} for {_area_name(lsoa)}", type="primary", key=f"live_go_{mode}")
    redo = again.button("Regenerate", key=f"live_redo_{mode}", disabled=key not in store,
                        help="Ignore the cached answer and write a new one.")
    if first or redo:
        with st.spinner("Writing the explanation, then checking every figure, rank and length…"):
            store[key] = live.explain(bundle, stakeholder, lsoa, mode, regenerate=redo)
    result = store.get(key)
    if result is None:
        return None
    if result.status == "limit":
        st.info(result.problems[0])
        return None
    if result.status == "error":
        st.warning("The AI service could not be reached just now. Please try again.")
        return None
    if result.status == "evidence_only":
        _evidence_only(bundle, stakeholder, lsoa, result)
        return None
    return result


def _meta(result) -> str:
    tries = "first attempt" if result.attempts == 1 else f"repaired after {result.attempts} attempts"
    return (f"Generated live by {html.escape(result.response.model)} at temperature 0 · {tries} · validated: every figure "
            f"and rank traced to the evidence, wording and length checked · not individually reviewed · "
            f"{html.escape(result.response.timestamp[:10])}")


def _evidence_only(bundle, stakeholder: str, lsoa: str, result) -> None:
    from dashboard.views.area_panel import _insights
    from dashboard.views.decision_support import decision_table
    from dashboard.views.maps import predictions_for

    table, predictions = decision_table(bundle), predictions_for(None)
    lines = _insights(table, lsoa, stakeholder, float(predictions.loc[lsoa, "predicted"]),
                      float(predictions["predicted"].mean()))
    bullets = "".join(f"<li>{html.escape(line)}</li>" for line in lines)
    with st.container(border=True):
        st.markdown(f"<div class='gs-kicker'>{html.escape(STAKEHOLDERS[stakeholder])} · Evidence-only summary, "
                    f"{html.escape(_area_name(lsoa))}</div><ul>{bullets}</ul>"
                    f"<div class='gs-foot'><span class='gs-meta'>The AI explanation did not pass validation after "
                    f"{result.attempts} attempts, so these lines are written directly from the evidence instead.</span></div>",
                    unsafe_allow_html=True)
        with st.expander("What failed validation"):
            for problem in result.problems:
                st.markdown(f"- {problem}")


def render_area_card(bundle, stakeholder: str, lsoa: str) -> None:
    result = _run_live(bundle, stakeholder, lsoa, "short", "card")
    if result is None:
        return
    d = stakeholder_data()
    panels = stakeholder_panels(f"{stakeholder}_area", lsoa, d.default_contrast(lsoa))
    _card(stakeholder, _area_name(lsoa), AREA_PANEL_TITLES[stakeholder], ("", ""), panels, result.content, 4,
          "Model attribution for this area.", _meta(result))


@st.cache_data(show_spinner=False)
def published_detailed(stakeholder: str) -> dict | None:
    path = HULL_ROOT / CARDS_DIR / f"{stakeholder}_detailed_llm.json"
    if not path.exists():
        return None
    run = json.loads(path.read_text(encoding="utf-8")).get("run") or {}
    return run if run.get("ok") and run["checks"]["ok"] else None


def render_detailed(stakeholder: str) -> None:
    run = published_detailed(stakeholder)
    if run is None:
        st.warning("The detailed narrative has not been published yet. Run generate_detailed_narrative.py.")
        return
    d = stakeholder_data()
    focus, contrast = cm.detailed_focus(d, stakeholder)
    meta = (f"Text generated by {html.escape(run['model'])} at temperature 0 · prompt {html.escape(run['prompt_version'])} "
            f"· {html.escape(run['timestamp'][:10])} · " + ("Checks passed" if run["checks"]["ok"] else
                                                          "Checks failed: " + "; ".join(run["checks"]["problems"])))
    _detailed(stakeholder, "Detailed narrative, Hull-wide", stakeholder_panels(stakeholder, focus, contrast), run["text"], meta)


# The page's interactive map already shows GeoSensitivity, so its static copy is left out here.
LOCATION_MAP_TITLES = {"Where it matters.", "Spatial view."}


def _detailed(stakeholder: str, kicker: str, panels, text: str, meta: str, body_html: str | None = None) -> None:
    panels = [p for p in panels if p[1] not in LOCATION_MAP_TITLES]
    with st.container(border=True):
        st.markdown(f"<div class='gs-kicker'>{html.escape(STAKEHOLDERS[stakeholder])} · {html.escape(kicker)}</div>",
                    unsafe_allow_html=True)
        left, right = st.columns([0.45, 0.55], gap="large")
        with left:
            for image, title, caption in panels:
                st.image(image, width="stretch")
                st.markdown(f"<div class='gs-caption'><b>{html.escape(title)}</b> {html.escape(caption)}</div>",
                            unsafe_allow_html=True)
        with right:
            st.markdown(f"<div class='gs-body'>{body_html or cm.marked_html(text)}</div>", unsafe_allow_html=True)
            st.markdown(f"<div class='gs-foot'><span class='gs-meta'>{meta}</span></div>", unsafe_allow_html=True)


def render_area_detailed(bundle, stakeholder: str, lsoa: str) -> None:
    result = _run_live(bundle, stakeholder, lsoa, "comprehensive", "detailed narrative")
    if result is None:
        return
    d, content = stakeholder_data(), result.content
    sections = "".join(
        f"<div class='gs-kicker' style='margin-top:.6rem;'>{html.escape(heading)}</div>{cm.marked_html(content[key])}"
        for heading, key in zip(live.HEADINGS[stakeholder], live.DETAILED_PARTS))
    fields = ", ".join(str(f) for f in content.get("evidence_fields") or [])
    body = (sections + f"<div class='gs-caption' style='margin-top:.6rem;'><b>Limitation.</b> "
            f"{html.escape(cm._bare(content['limitation']))}</div>"
            + (f"<div class='gs-caption'><b>Evidence used:</b> {html.escape(fields)}</div>" if fields else ""))
    _detailed(stakeholder, f"Detailed narrative, {_area_name(lsoa)}",
              stakeholder_panels(stakeholder, lsoa, d.default_contrast(lsoa)), "", _meta(result), body_html=body)


def render_comparison() -> None:
    st.markdown("<div class='gs-lede'>One model and one evidence base, six explanatory roles. "
                "Each role receives different evidence, not simpler or harder wording.</div>", unsafe_allow_html=True)
    cols = st.columns(2, gap="medium")
    for i, (stakeholder, label) in enumerate(STAKEHOLDERS.items()):
        run = published_card(stakeholder)
        with cols[i % 2], st.container(border=True):
            st.markdown(f"<div class='gs-kicker'>{html.escape(label)}</div>", unsafe_allow_html=True)
            if run is None:
                st.caption("Not published yet.")
                continue
            n_tiles = CARD_LAYOUT[stakeholder][3]
            st.markdown(f"<div class='gs-headline gs-headline-small'>{_inline(run['content']['headline'])}</div>"
                        + _tiles(run["content"]["tiles"][:n_tiles]), unsafe_allow_html=True)
