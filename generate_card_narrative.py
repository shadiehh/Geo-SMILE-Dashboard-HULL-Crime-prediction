"""LLM-generated content for a Chapter 6 stakeholder card (planner, police, ...).

    python generate_card_narrative.py --stakeholder police [--force] [--openai-model gpt-4.1]

The prompt addenda, evidence blocks, checks and LaTeX markup live in
dashboard.llm.card_mode (SPECS), so each thesis card and the dashboard's short narrative for
that stakeholder use one definition. Pipeline:
  evidence  dashboard.llm.evidence_builder.build_evidence(stakeholder, Hull-wide)
            plus card_mode.add_evidence (the stakeholder's card block);
  system    GEOSMILE_SYSTEM_PROMPT (master prompt, unchanged) + the stakeholder's card addendum;
  user      the card question, the evidence JSON and the illustrative narrative;
  models    the providers and models configured in .env, temperature 0.

Writes outputs/stakeholder_narratives/<stakeholder>_card_llm.json (prompts, evidence, raw
output, checks per provider) and <stakeholder>_card_llm_content_<provider>.tex (macros used by
<stakeholder>_card.tex). An existing JSON is reused so the published text does not change on
rerun; --force regenerates it after archiving the previous run as
<stakeholder>_card_llm_attempt<k>.json.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shutil
from datetime import datetime, timezone
from pathlib import Path

from dotenv import load_dotenv

from dashboard.llm import card_mode as cm

ROOT = Path(__file__).resolve().parent
DEST = ROOT / "outputs" / "stakeholder_narratives"


def out_json(stakeholder: str) -> Path:
    return DEST / f"{stakeholder}_card_llm.json"


def build(stakeholder: str) -> tuple[dict, str, str]:
    from dashboard.data.loader import load_hull_bundle
    from dashboard.data.stakeholder_data import load_stakeholder_data
    from dashboard.llm.evidence_builder import build_evidence, user_payload
    from dashboard.llm.prompt import GEOSMILE_SYSTEM_PROMPT

    spec = cm.SPECS[stakeholder]
    evidence = build_evidence(load_hull_bundle(), stakeholder_id=stakeholder, current_map_view="geo_sensitivity",
                              scope="hull", selected_lsoa=None, user_question=spec["question"],
                              output_mode="dashboard_mode")
    cm.add_evidence(evidence, load_stakeholder_data(), stakeholder, "short")
    system = GEOSMILE_SYSTEM_PROMPT + "\n" + spec["addenda"]["short"]
    user = user_payload(evidence, spec["question"]) + cm.user_suffix("short", stakeholder)
    return evidence, system, user


def call_openai(system: str, user: str) -> tuple[str, str]:
    from openai import OpenAI

    model = os.getenv("OPENAI_MODEL", "gpt-4.1-mini")
    resp = OpenAI(api_key=os.environ["OPENAI_API_KEY"].strip().strip('"'), timeout=90).chat.completions.create(
        model=model, temperature=0, response_format={"type": "json_object"},
        messages=[{"role": "system", "content": system}, {"role": "user", "content": user}])
    return model, resp.choices[0].message.content


def call_anthropic(system: str, user: str) -> tuple[str, str]:
    import anthropic

    model = os.getenv("ANTHROPIC_MODEL", "claude-sonnet-4-5")
    resp = anthropic.Anthropic(api_key=os.environ["ANTHROPIC_API_KEY"].strip().strip('"'), timeout=90).messages.create(
        model=model, max_tokens=1500, temperature=0, system=system,
        messages=[{"role": "user", "content": user}])
    return model, "".join(b.text for b in resp.content if b.type == "text")


def write_tex(stakeholder: str, name: str, run: dict) -> Path:
    c = run["content"]
    lines = [f"% Generated by {run['provider']} {run['model']} on {run['timestamp']}, prompt "
             f"{run['prompt_version']} + card-mode addendum, temperature 0 "
             f"(generate_card_narrative.py --stakeholder {stakeholder}). Checks: "
             f"{'passed' if run['checks']['ok'] else '; '.join(run['checks']['problems'])}. Do not edit by hand.",
             rf"\renewcommand{{\cardHeadline}}{{{cm.marked_tex(c['headline'])}}}",
             rf"\renewcommand{{\cardSecA}}{{{cm.marked_tex(c['section_01'])}}}",
             rf"\renewcommand{{\cardSecB}}{{{cm.marked_tex(c['section_02'])}}}",
             rf"\renewcommand{{\cardFooter}}{{{cm.tex_escape(c['footer'])}}}",
             rf"\renewcommand{{\cardModel}}{{{cm.tex_escape(run['model'])}}}"]
    for letter, t in zip("ABCD", c["tiles"][:4]):
        lines.append(rf"\renewcommand{{\cardTile{letter}}}{{\tile{{{cm.tex_escape(t['value'])}}}"
                     rf"{{{cm.tex_escape(t['label'])}}}}}")
    path = DEST / f"{stakeholder}_card_llm_content_{name}.tex"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def generate(stakeholder: str) -> dict:
    from dashboard.llm.prompt import SYSTEM_PROMPT_VERSION

    spec = cm.SPECS[stakeholder]
    evidence, system, user = build(stakeholder)
    record = {"previous_attempts": [a.name for a in sorted(DEST.glob(f"{stakeholder}_card_llm_attempt*.json"))],
              "stakeholder": stakeholder, "question": spec["question"], "prompt_version": SYSTEM_PROMPT_VERSION,
              "card_mode_addendum": spec["addenda"]["short"], "illustrative_narrative": spec["example"],
              "evidence": evidence, "runs": {}}
    for name, call in (("openai", call_openai), ("anthropic", call_anthropic)):
        stamp = datetime.now(timezone.utc).isoformat()
        try:
            model, raw = call(system, user)
            content = cm.parse_card(raw)
            record["runs"][name] = {"ok": True, "provider": name, "model": model, "timestamp": stamp,
                                    "prompt_version": SYSTEM_PROMPT_VERSION, "raw": raw, "content": content,
                                    "checks": cm.check(content, evidence, "short", spec.get("limits"))}
        except Exception as exc:  # recorded, not retried
            msg = re.sub(r"sk-[A-Za-z0-9_-]+", "<key>", str(exc))[:300]
            record["runs"][name] = {"ok": False, "provider": name, "timestamp": stamp, "error": f"{type(exc).__name__}: {msg}"}
        print(f"{name}: {'ok' if record['runs'][name]['ok'] else record['runs'][name]['error']}")
    return record


def archive(stakeholder: str) -> None:
    """Keep the run being replaced as the next <stakeholder>_card_llm_attempt<k>.json."""
    path = out_json(stakeholder)
    if path.exists():
        k = len(list(DEST.glob(f"{stakeholder}_card_llm_attempt*.json"))) + 1
        shutil.copy(path, DEST / f"{stakeholder}_card_llm_attempt{k}.json")


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--stakeholder", required=True, choices=sorted(cm.SPECS))
    parser.add_argument("--force", action="store_true", help="regenerate even if the JSON exists")
    parser.add_argument("--openai-model", help="override OPENAI_MODEL from .env for this card")
    args = parser.parse_args(argv)
    load_dotenv(ROOT / ".env", override=True)
    if args.openai_model:
        os.environ["OPENAI_MODEL"] = args.openai_model
    path = out_json(args.stakeholder)
    if path.exists() and not args.force and "runs" in json.loads(path.read_text(encoding="utf-8")):
        record = json.loads(path.read_text(encoding="utf-8"))
        print(f"Reusing {path}")
    else:
        archive(args.stakeholder)
        record = generate(args.stakeholder)
        path.write_text(json.dumps(record, indent=2, ensure_ascii=False, default=str), encoding="utf-8")
        print(f"Saved {path}")
    for name, run in record["runs"].items():
        if run["ok"]:
            print(f"\n[{name} {run['model']}] checks: {run['checks']}")
            print(json.dumps(run["content"], indent=1, ensure_ascii=False))
            print("->", write_tex(args.stakeholder, name, run).name)


if __name__ == "__main__":
    main()
