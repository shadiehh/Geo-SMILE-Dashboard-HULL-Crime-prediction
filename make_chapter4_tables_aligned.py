"""Chapter-4 tables for the Seattle/Chicago-aligned Hull design, in the chapter's own layout.

Reads outputs/geo_aligned_design/ (hull_aligned_design_eval.py) and writes
outputs/geo_aligned_design/chapter4_tables_aligned.tex (also copied to
outputs/hull_geo_design_review/05_aligned_design/). Table labels carry the suffix "_aligned" so the
file can sit beside the published tables. Not causal.

    python make_chapter4_tables_aligned.py
"""
from __future__ import annotations

import json
import shutil
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent
SRC = ROOT / "outputs" / "geo_aligned_design"
COPY = ROOT / "outputs" / "hull_geo_design_review" / "05_aligned_design"
NS = (1000, 2000, 3000, 4000, 5000, 7500, 10000)
ORDER = ["gp", "transformer", "catboost", "lightgbm", "xgboost", "ann", "svr", "cnn", "dl", "mlp"]
SHORT = {"gp": "GP", "transformer": "Trans.", "catboost": "CatB.", "lightgbm": "LGBM", "xgboost": "XGB",
         "ann": "ANN", "svr": "SVR", "cnn": "CNN", "dl": "Keras", "mlp": "MLP"}
LONG = {"xgboost": "XGBoost", "lightgbm": "LightGBM", "catboost": "CatBoost", "gp": "Gaussian process",
        "svr": "SVR", "ann": "ANN", "cnn": "CNN", "mlp": "MLP", "transformer": "Transformer", "dl": "Keras (deep)"}
FAMILIES = [("Tree ensemble", ["lightgbm", "xgboost", "catboost"]), ("Kernel", ["gp", "svr"]),
            ("Neural", ["ann", "cnn", "mlp", "transformer", "dl"])]
MENU_ROWS = [["Weighted OLS", "Weighted Ridge", "Bayesian ridge", "Linear regression", "Ridge (unweighted)",
              "Elastic net (weak)", "Kernel ridge (RBF)", "Hist. grad. boosting", "Random forest", "Tweedie GLM", "Poisson GLM"],
             ["Unweighted OLS", "Ridge $\\alpha=0$", "Shallow tree"], ["Null, SD"]]
DESIGN = ("aligned design: one XGBoost model on the 30 predictors plus BNG easting/northing; Feature masking "
          "keeps true coordinates; Geo masking moves only an LSOA's coordinates to the training-median point")


def f(v, d=4):
    return f"{v:.{d}f}"


def table(label, caption, colspec, header, rows, size="\\small", resize=False):
    body = "\n".join(rows)
    inner = f"\\begin{{tabular}}{{{colspec}}}\n\\toprule\n{header} \\\\\n\\midrule\n{body}\n\\bottomrule\n\\end{{tabular}}"
    if resize:
        inner = f"\\resizebox{{\\textwidth}}{{!}}{{%\n{inner}}}"
    return (f"\\begin{{table}}[H]\n\\centering\n\\caption{{{caption}}}\n\\label{{{label}}}\n{size}\n{inner}\n"
            f"\\end{{table}}\n")


def main() -> None:
    models = {m: json.loads((SRC / "models" / f"{m}.json").read_text()) for m in ORDER}
    xg = {n: json.loads((SRC / "xgboost" / f"n_{n}.json").read_text()) for n in NS}
    p = xg[4000]
    F, G = p["feature"], p["geo"]
    corr = pd.read_csv(SRC / "models" / "att_faithfulness.csv")
    out = [f"% Chapter-4 tables, {DESIGN}.\n% Generated by make_chapter4_tables_aligned.py from outputs/geo_aligned_design/. Not causal.\n"]

    # Stage 1
    top4 = sorted(ORDER, key=lambda m: -models[m]["predictive"]["r2"])[:4]
    rows = []
    for fam, ms in FAMILIES:
        for i, m in enumerate(ms):
            r = models[m]["predictive"]
            r2 = f(r["r2"]) if m not in top4 else f"\\textbf{{{f(r['r2'])}}}"
            rows.append(f"{'\\multirow{%d}{*}{%s}' % (len(ms), fam) if i == 0 else ''} & {LONG[m]} & {f(r['mae'])} & {f(r['rmse'])} & {r2} \\\\")
        rows.append("\\midrule")
    out.append(table("tab:sel_pred_aligned", "Stage 1, held-out predictive performance for candidate models on the 30 "
                     "predictors plus the two centroid coordinates (aligned design).", "llrrr",
                     "Family & Model & MAE & RMSE & $R^2$", rows[:-1]))

    # Surrogate menus
    for branch, label, title in (("feature", "tab:fid_feat_aligned", "Feature"), ("geo", "tab:fid_geo_aligned", "Geo")):
        menu = {m: {s["surrogate"]: s for s in models[m][f"{branch}_menu"]} for m in ORDER}
        rows = []
        for gi, group in enumerate(MENU_ROWS):
            for name in group:
                cells = []
                for m in ORDER:
                    v = menu[m][name]["r2"]
                    cells.append(f"\\textbf{{{f(v)}}}" if (name == "Weighted Ridge" and m == "xgboost") else f(v))
                rows.append(f"{name} & " + " & ".join(cells) + " \\\\")
            if gi < len(MENU_ROWS) - 1:
                rows.append("\\midrule")
        out.append(table(label, f"{title} branch fidelity results for candidate surrogates ($N=4{{,}}000$ "
                         "perturbations; aligned design).", "l" + "r" * 10,
                         "Surrogate & " + " & ".join(SHORT[m] for m in ORDER), rows, size="\\scriptsize", resize=True))

    # Weighted Ridge, both branches
    rows = []
    for fam, ms in FAMILIES:
        for i, m in enumerate(ms):
            fr = next(s for s in models[m]["feature_menu"] if s["surrogate"] == "Weighted Ridge")
            gr = next(s for s in models[m]["geo_menu"] if s["surrogate"] == "Weighted Ridge")
            vals = " & ".join(f(x[k]) for x in (fr, gr) for k in ("r2", "mae", "wmae", "rmse", "wrmse"))
            rows.append(f"{'\\multirow{%d}{*}{%s}' % (len(ms), fam) if i == 0 else ''} & {LONG[m]} & {vals} \\\\")
        rows.append("\\midrule")
    out.append(table("tab:ridge_fidelity_full_aligned", "Weighted Ridge surrogate fidelity, all ten models, both "
                     "branches ($N=4{,}000$ perturbations each; aligned design).", "llrrrrrrrrrr",
                     "& & \\multicolumn{5}{c}{Feature} & \\multicolumn{5}{c}{Geo} \\\\\n\\cmidrule(lr){3-7}\\cmidrule(lr){8-12}\n"
                     "Family & Model & $R^2$ & MAE & WMAE & RMSE & WRMSE & $R^2$ & MAE & WMAE & RMSE & WRMSE",
                     rows[:-1], size="\\scriptsize", resize=True))

    # Fidelity by N
    rows = []
    for n in NS:
        a, b = xg[n]["feature"]["fidelity"], xg[n]["geo"]["fidelity"]
        cells = [f"{n:,}", f(a["R2"]), f(a["Weighted R2"]), f(b["R2"]), f(b["Weighted R2"])]
        rows.append(" & ".join(f"\\textbf{{{c}}}" for c in cells) + " \\\\" if n == 4000 else " & ".join(cells) + " \\\\")
    out.append(table("tab:hull_fidelity_by_n_aligned", "Held-out Geo-SMILE weighted-Ridge fidelity by perturbation "
                     "count (aligned design)", "rrrrr", "$N$ & Feature $R^2$ & Feature weighted $R^2$ & Geo $R^2$ & Geo weighted $R^2$", rows))

    # Rule robustness
    rows = []
    for name, a in G["accuracy_rule_robustness"].items():
        if name.startswith("published"):
            continue
        nm = name.replace(">=", "$\\ge$").replace("%", "\\%").replace("km2", "km$^2$")
        rows.append(f"{nm} & {a['reference_size']} & {a['intersection']} & {f(a['chance'], 3)} & {f(a['lift'], 2)} & {a['p_hypergeom']:.2g} \\\\")
    out.append(table("tab:hull_region_rule_robustness_aligned", "Robustness of Geo ATT accuracy ($k=20$, XGBoost, "
                     "$N=4{,}000$; aligned design) to the rule assigning LSOAs to the expert-highlighted regions. "
                     "Chance is the reference share of the 168 LSOAs; $p$ is the one-sided hypergeometric probability "
                     "of at least the observed count.", "lrrrrr",
                     "Inclusion rule & Reference LSOAs & Top-20 inside & Chance & Lift & $p$", rows))

    # Accuracy
    fa, ga = F["accuracy"], G["accuracy"]
    fchance = 10 / 30
    rows = [f"$n$ & 30 & {ga['reference_size'] and 168} \\\\", f"Reference size & 10 & {ga['reference_size']} \\\\",
            "$k$ & 10 & 20 \\\\", f"Intersection & {fa['intersection']} & {ga['intersection']} \\\\",
            f"Accuracy & {f(fa['intersection'] / 10)} & {f(ga['accuracy'])} \\\\",
            f"Chance accuracy & {f(fchance)} & {f(ga['chance'])} \\\\",
            f"Lift & {f(fa['intersection'] / 10 / fchance, 2)} & {f(ga['lift'], 2)} \\\\",
            f"ATT ACC & {f(fa['accuracy'])} & {f(ga['att_acc'])} \\\\", f"ATT F1 & {f(fa['f1'])} & {f(ga['att_f1'])} \\\\",
            f"ATT AUROC & {f(fa['auroc'])} & {f(ga['att_auroc'])} \\\\",
            f"Precision@$k$ & {f(fa['precision'])} & {f(ga['precision'])} \\\\",
            f"Recall@$k$ & {f(fa['recall'])} & {f(ga['recall'])} \\\\",
            f"Jaccard@$k$ & {f(fa['jaccard_at_k'])} & {f(ga['jaccard'])} \\\\"]
    out.append(table("tab:hull_att_accuracy_primary_aligned", "Primary ATT accuracy at the final $N=4{,}000$ design "
                     "(aligned design). Feature: top 10 against the 10-predictor reference. Geo: top 20 against the 58 "
                     "LSOAs in the expert-highlighted regions.", "lcc", "Metric & Feature & Geo", rows))

    # Faithfulness
    rows = []
    allm = corr[corr["subset"] == "all"]
    for _, r in allm.iterrows():
        tag = "primary" if "accuracy" in r["measure"] else "secondary"
        rows.append(f"{r['branch']} & {r['measure']}, {tag} & {int(r['M'])} & {r['pearson_r']:.2f} & {r['p_two_sided']:.2f} & {r['spearman_rho']:.2f} \\\\")
    out.append(table("tab:hull_faithfulness_correlation_aligned", "ATT Faithfulness in the Hull experiment (aligned "
                     "design): Pearson correlation, across the candidate models, between predictive $R^2$ and ATT "
                     "accuracy (primary), with ATT-AUC as a secondary attribution-quality measure.", "llrrrr",
                     "Branch & Attribution measure & $M$ & Pearson $r$ & Two-sided $p$ & Spearman $\\rho$", rows))
    sub = corr[corr["subset"] != "all"]
    out.append("% Without dl and cnn (M = 8): " + "; ".join(
        f"{r['branch']} {r['measure']}: r = {r['pearson_r']:.2f}, p = {r['p_two_sided']:.2f}" for _, r in sub.iterrows()) + "\n")

    # Stability
    dirs = ("north", "east", "south", "west")
    fs, gs = F["stability"]["directions"], G["stability"]["directions"]
    rows = ["Feature & " + " & ".join(f"{f(fs[d]['jaccard'], 3)} & {f(fs[d]['spearman_abs'])}" for d in dirs) + " \\\\",
            "Geo & " + " & ".join(f"{f(gs[d]['jaccard'], 3)} & {f(gs[d]['spearman'])}" for d in dirs) + " \\\\"]
    out.append(table("tab:hull_att_stability_aligned", "ATT stability at $N=4{,}000$ (seed 42) under one-LSOA additions "
                     "in the four cardinal directions (aligned design).", "lcc|cc|cc|cc",
                     "Branch & North Jac. & North $\\rho$ & East Jac. & East $\\rho$ & South Jac. & South $\\rho$ & West Jac. & West $\\rho$",
                     rows, size="\\scriptsize", resize=True))
    rows = [f"{d.capitalize()} & \\texttt{{{gs[d]['lsoa21cd']}}} & {gs[d]['added_rank']} & ${gs[d]['added_coefficient']:+.4f}$ & "
            f"{'Yes' if gs[d]['added_in_top20'] else 'No'} \\\\" for d in dirs]
    out.append(table("tab:hull_att_stability_extra_aligned", "Geo-SMILE attribution ranks of the added LSOAs in the "
                     "cardinal-direction stability experiment (aligned design).", "llccc",
                     "Addition & LSOA code & Extra rank & Extra coef. & In top-20", rows))
    w = G["fixed_kernel_west"]
    out.append(f"% Fixed-kernel west: Jaccard {w['jaccard']:.3f}, rho {w['spearman']:.4f}, added rank {w['added_rank']}, "
               f"top-20 retained {w['top20_retained']}/20. Prediction-order Spearman (Feature): "
               + ", ".join(f"{fs[d]['prediction_spearman']:.3f}" for d in dirs) + ".\n")

    # Consistency
    fc, gc = F["consistency"], G["consistency"]
    rows = [f"Feature & {fc['mean_variance']:.6f} & {fc['median_variance']:.6f} & {fc['mean_sd']:.5f} & {fc['median_sd']:.5f} & {fc['max_sd']:.5f} \\\\",
            f"Geo & {gc['mean_variance']:.2e} & {gc['median_variance']:.2e} & {gc['mean_sd']:.5f} & {gc['median_sd']:.5f} & {gc['max_sd']:.5f} \\\\"]
    out.append(table("tab:hull_consistency_variance_aligned", "ATT consistency of Geo-SMILE coefficients across "
                     "independently seeded perturbation runs (aligned design)", "l|rrrrr",
                     "Branch & Mean variance & Median variance & Mean SD & Median SD & Maximum SD", rows))
    out.append(f"% Feature max SD: {fc['max_sd_feature']}; leading coefficients (mean, SD): "
               + "; ".join(f"{k} {v['mean_coefficient']:.4f} ({v['sd']:.4f})" for k, v in fc["leading_features_mean_sd"].items())
               + f". Geo max SD: {gc['max_sd_lsoa']} ({gc['max_sd_lsoa_name']}), mean coefficient {gc['max_sd_lsoa_mean_coefficient']:.4f}, "
               f"SD = {gc['max_sd_pct_of_mean']:.2f}% of mean. Rank Spearman / score Pearson / top-20% Jaccard: Feature "
               f"{fc['rank_spearman_mean']:.3f} / {fc['score_pearson_mean']:.4f} / {fc['top20pct_jaccard_mean']:.3f}; Geo "
               f"{gc['rank_spearman_mean']:.3f} / {gc['score_pearson_mean']:.4f} / {gc['top20pct_jaccard_mean']:.3f}.\n")

    # Intervention
    fi, gi = F["intervention"], G["intervention"]
    rows = [f"$k$ & {fi['k']} & {gi['k']} \\\\", f"Top response & {f(fi['top_response'])} & {f(gi['top_response'])} \\\\",
            f"Bottom response & {f(fi['bottom_response'])} & {f(gi['bottom_response'])} \\\\",
            f"Random mean & {f(fi['random_mean'])} & {f(gi['random_mean'])} \\\\",
            f"Random 95\\% interval & {f(fi['random_ci95_low'])}--{f(fi['random_ci95_high'])} & {f(gi['random_ci95_low'])}--{f(gi['random_ci95_high'])} \\\\",
            f"Top--random & {f(fi['top_minus_random'])} & {f(gi['top_minus_random'])} \\\\",
            f"Top--bottom & {f(fi['top_minus_bottom'])} & {f(gi['top_minus_bottom'])} \\\\",
            f"Empirical $p$ & {f(fi['empirical_p_top_vs_random'])} & {f(gi['empirical_p_top_vs_random'])} \\\\",
            "Random sets & 1,000 & 1,000 \\\\"]
    out.append(table("tab:hull_intervention_impact_aligned", "Intervention-based attribution impact for the final "
                     "$N=4{,}000$ XGBoost explanation (aligned design).", "lcc", "Metric & Feature & Geo", rows))

    # Metrics by N
    rows = []
    for bi, (branch, k) in enumerate((("feature", 10), ("geo", 20))):
        for i, n in enumerate(NS):
            b = xg[n][branch]
            cells = [f"{n:,}", f(b["fidelity"]["R2"]), f"{b['accuracy']['intersection']}/{k}",
                     f(b["intervention"]["top_minus_random"], 3), f(b["stability"]["jaccard_mean"], 3),
                     f"{b['consistency']['mean_variance']:.2e}" if branch == "geo" else f"{b['consistency']['mean_variance']:.6f}",
                     f(b["consistency"]["mean_sd"], 5)]
            if n == 4000:
                cells = [f"\\textbf{{{c}}}" for c in cells]
            lead = f"\\multirow{{7}}{{*}}{{{branch.capitalize()}}}" if i == 0 else ""
            rows.append(f"{lead}\n& " + " & ".join(cells) + " \\\\")
        if bi == 0:
            rows.append("\\midrule")
    out.append(table("tab:hull_metrics_by_n_aligned", "Evaluation diagnostics across independent perturbation budgets "
                     "for the XGBoost Feature and Geo branches (aligned design). ATT accuracy is the top-10 reference "
                     "overlap for Feature and the top-20 share inside the expert-highlighted regions for Geo; "
                     "Intervention $\\Delta W_1$ is the top-$k$ minus random-set response.", "@{}lrcccccc@{}",
                     "Branch & $N$ & \\shortstack{Fidelity\\\\$R^2$} & \\shortstack{ATT\\\\accuracy} & "
                     "\\shortstack{Intervention\\\\$\\Delta W_1$} & \\shortstack{Stability\\\\Jaccard} & "
                     "\\shortstack{Consistency\\\\mean variance} & \\shortstack{Consistency\\\\mean SD}",
                     rows, resize=True))

    # Text numbers
    top10 = ", ".join(f"\\texttt{{{x['feature'].replace('_', '\\_')}}} (${x['coefficient']:.4f}$)" for x in F["importance"][:10])
    gtop = ", ".join(f"\\texttt{{{x['lsoa21cd']}}} ({x['lsoa21nm'].replace('Kingston upon Hull ', '')}, ${x['geo_coefficient']:.4f}$)" for x in G["top10"][:5])
    out.append(
        "% ---- Numbers quoted in the text (aligned design, XGBoost, N = 4,000) ----\n"
        f"% Predictive model: R2 = {p['predictive']['r2']:.4f}, MAE = {p['predictive']['mae']:.3f}, RMSE = {p['predictive']['rmse']:.3f}.\n"
        f"% Feature top 10 (signed coefficient): {top10}.\n"
        f"% Mapped local drivers: {', '.join(F['mapped_top6'])}.\n"
        f"% Feature concentration: Hoyer {F['concentration']['hoyer']:.4f}, Gini {F['concentration']['gini']:.4f}, entropy {F['concentration']['entropy']:.4f}.\n"
        f"% Geo top 5: {gtop}.\n"
        f"% Geo signed vs single-LSOA W1 shift rho_s = {G['exact_vs_signed_spearman']:.3f}; |beta| rho_s = {G['exact_vs_abs_spearman']:.2f}; "
        f"shift median {G['exact_w1_median']:.2f}, 90th percentile {G['exact_w1_p90']:.2f} crimes/month; mean coalition W1 {G['mean_W1_response']:.3f}; "
        f"{G['n_negative']} negative coefficients.\n"
        f"% Geo concentration (single-LSOA shift): Hoyer {G['concentration_exact_shift']['hoyer']:.4f}, Gini {G['concentration_exact_shift']['gini']:.4f}, "
        f"entropy {G['concentration_exact_shift']['entropy']:.4f}.\n"
        f"% Moran's I = {G['moran']['I']:.3f} (p = {G['moran']['p_sim']:.3f}, queen, 999 permutations); LISA counts {G['moran']['lisa_counts']}.\n"
        f"% Geo accuracy k = 42: {G['accuracy_k']['42']['intersection']} (lift {G['accuracy_k']['42']['lift']:.2f}, p = {G['accuracy_k']['42']['p_hypergeom']:.3f}); "
        f"k = 50: {G['accuracy_k']['50']['intersection']} (lift {G['accuracy_k']['50']['lift']:.2f}, p = {G['accuracy_k']['50']['p_hypergeom']:.3f}).\n"
        f"% Geo top-20 outside the reference: {', '.join(G['accuracy']['top_k_outside_reference'])}.\n"
        f"% Spearman with the published area-data Geo ranking: {G['spearman_with_area_data_geo']:.2f}.\n")
    text = "\n".join(out)
    dest = SRC / "chapter4_tables_aligned.tex"
    dest.write_text(text, encoding="utf-8")
    COPY.mkdir(parents=True, exist_ok=True)
    shutil.copy2(dest, COPY / dest.name)
    print("Wrote", dest)


if __name__ == "__main__":
    main()
